#!/usr/bin/env python
"""Regenerate every LaTeX table (report/tables) and figure (report/figures) from results/.

Idempotent. Missing inputs are skipped with a printed note; re-run (`make figures`) once they land.
Never invents numbers: every value is read from a file under results/.
"""
import csv
import glob
import json
import os
import statistics as st

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
TAB = os.path.join(ROOT, "report", "tables")
FIG = os.path.join(ROOT, "report", "figures")
os.makedirs(TAB, exist_ok=True)
os.makedirs(FIG, exist_ok=True)
MISSING = []
OKABE = ["#0072B2", "#E69F00", "#009E73", "#D55E00", "#CC79A7", "#56B4E9", "#F0E442", "#000000"]
plt.rcParams.update({"font.size": 8, "axes.labelsize": 8, "legend.fontsize": 7, "pdf.fonttype": 42,
                     "axes.spines.top": False, "axes.spines.right": False})

CLS_ORDER = ["included", "not included", "excluded", "not excluded", "not enough information", "not applicable"]


def esc(s):
    s = str(s)
    for a, b in [("\\", "\\textbackslash{}"), ("_", "\\_"), ("%", "\\%"), ("&", "\\&"), ("#", "\\#")]:
        s = s.replace(a, b)
    return s


def jload(rel):
    p = os.path.join(R, rel)
    if not os.path.exists(p):
        MISSING.append(rel)
        print(f"[skip] missing {rel}")
        return None
    with open(p) as f:
        return json.load(f)


def cload(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def latest(pattern):
    xs = sorted(glob.glob(os.path.join(R, pattern)))
    if not xs:
        MISSING.append(pattern)
        print(f"[skip] no match for {pattern}")
        return None
    return xs[-1]


def f(x, n=3):
    return "--" if x is None else f"{x:.{n}f}"


def table(name, src, body, caption, label, wide=False):
    """body: tabular environment text. Wrapped in table float + \\small."""
    inner = body if not wide else "\\resizebox{\\columnwidth}{!}{%\n" + body + "}"
    txt = (f"% GENERATED by scripts/make_figures.py from: {src}\n"
           f"\\begin{{table}}[t]\\centering\\small\n\\caption{{{caption}}}\\label{{{label}}}\n{inner}\n\\end{{table}}\n")
    with open(os.path.join(TAB, name + ".tex"), "w") as fh:
        fh.write(txt)
    print(f"[ok] tables/{name}.tex")


def tab(cols, header, rows):
    out = "\\begin{tabular}{" + cols + "}\n\\toprule\n" + " & ".join(header) + " \\\\\n\\midrule\n"
    for r in rows:
        out += (r if isinstance(r, str) else " & ".join(r) + " \\\\") + "\n"
    return out + "\\bottomrule\n\\end{tabular}"


KEEP = {"label_distribution", "spec_speedup"}  # produced earlier by other scripts; never overwritten


def savefig(fig, name):
    if name in KEEP and os.path.exists(os.path.join(FIG, name + ".pdf")):
        plt.close(fig)
        print(f"[keep] figures/{name}.pdf exists")
        return
    fig.savefig(os.path.join(FIG, name + ".pdf"), bbox_inches="tight")
    plt.close(fig)
    print(f"[ok] figures/{name}.pdf")


