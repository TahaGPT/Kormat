def speculative():
    eqd = latest("speculative/*equiv*")
    bd = latest("speculative/*bench_A")
    parts = []
    if eqd:
        m = json.load(open(os.path.join(eqd, "metrics.json")))
        rr = m["rows"]
        meths = sorted({r["method"] for r in rr})
        rows = []
        for me in meths:
            xs = [r for r in rr if r["method"] == me]
            rows.append([esc(me), f"{sum(bool(r['exact']) for r in xs)}/{len(xs)}",
                         f(st.mean(r["alpha"] for r in xs if isinstance(r.get("alpha"), float)), 2)
                         if any(isinstance(r.get("alpha"), float) for r in xs) else "--"])
        table("speculative_equiv", os.path.relpath(eqd, ROOT) + "/metrics.json",
              tab("lrr", ["Method", "Token-exact", "Mean accept.\\ rate"], rows),
              "Speculative decoding correctness: output identical to greedy decoding of the target model.",
              "tab:speceq")
        parts.append("\\input{tables/speculative_equiv}\n")
    if bd:
        rr = cload(os.path.join(bd, "bench_A.csv"))
        base = {r["prompt"]: float(r["total_tok_s"]) for r in rr if r["method"] == "greedy_kv"}
        rows = []
        gam = sorted({int(r["gamma"]) for r in rr if r["method"] == "spec"})
        g0 = [float(r["total_tok_s"]) for r in rr if r["method"] == "greedy_kv"]
        rows.append(["greedy (KV)", "--", "--", f(st.median(g0), 2), "1.00",
                     f"{sum(r['exact']=='True' for r in rr if r['method']=='greedy_kv')}/{len(g0)}"])
        for g in gam:
            xs = [r for r in rr if r["method"] == "spec" and int(r["gamma"]) == g]
            acc = sum(int(r["accepted"]) for r in xs) / sum(int(r["drafted"]) for r in xs)
            tps = [float(r["total_tok_s"]) for r in xs]
            sp = [float(r["total_tok_s"]) / base[r["prompt"]] for r in xs]
            ex = sum(r["exact"] == "True" for r in xs)
            rows.append(["speculative", str(g), f(acc, 2), f(st.median(tps), 2), f(st.median(sp), 2),
                         f"{ex}/{len(xs)}"])
        table("speculative_bench", os.path.relpath(bd, ROOT) + "/bench_A.csv",
              tab("lrrrrr", ["Method", "$\\gamma$", "Accept.\\ rate", "tok/s (median)", "Speed-up (median)",
                             "Exact"], rows),
              f"Speculative decoding (0.5B draft, 1.5B target, CPU), {len(g0)} prompts. Acceptance rate = "
              "accepted/drafted tokens pooled; tok/s counts prefill and decode; speed-up is per-prompt relative "
              "to greedy KV decoding.", "tab:specbench", wide=True)
        parts.append("\\input{tables/speculative_bench}\n")
        fig, ax = plt.subplots(figsize=(3.4, 2.2))
        ax.plot(gam, [st.median(float(r["total_tok_s"]) / base[r["prompt"]] for r in rr
                                if r["method"] == "spec" and int(r["gamma"]) == g) for g in gam], "o-",
                color=OKABE[0])
        ax.axhline(1, color="k", lw=0.5, ls="--")
        ax.set_xlabel("Draft length $\\gamma$ (tokens)")
        ax.set_ylabel("Speed-up vs greedy KV (x)")
        savefig(fig, "spec_speedup")
    if parts:
        with open(os.path.join(TAB, "speculative.tex"), "w") as fh:
            fh.write("% GENERATED by scripts/make_figures.py from results/speculative/**\n" + "".join(parts))
        print("[ok] tables/speculative.tex")


