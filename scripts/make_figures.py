def kvcache():
    eq = latest("kvcache/*equiv*/equivalence.csv")
    kv = latest("kvcache/*bench_kv/summary.json")
    nc = latest("kvcache/*bench_nocache/summary.json")
    body = ""
    if eq:
        rr = cload(eq)
        rows = [[r["dtype"], r["P_actual"], r["N"], "yes" if r["exact_match"] == "True" else "no",
                 f"{float(r['max_abs_dlogit_step0']):.1e}", f"{float(r['max_abs_dlogit_upto_div']):.1e}"]
                for r in rr]
        table("kvcache_equiv", os.path.relpath(eq, ROOT),
              tab("lrrcrr", ["dtype", "Prompt $P$", "New $N$", "Token-exact", "$|\\Delta$logit$|$ step 0",
                             "$|\\Delta$logit$|$ max"], rows),
              "KV-cache correctness: greedy generation with and without cache; exact token match and maximum "
              "absolute logit difference.", "tab:kveq", wide=True)
    sk = json.load(open(kv)) if kv else []
    sn = json.load(open(nc)) if nc else []
    if sk or sn:
        by = {(r["mode"], r["P"], r["N"]): r for r in sk + sn}
        keys = sorted({(r["P"], r["N"]) for r in sk + sn})
        rows = []
        for P, N in keys:
            a, b = by.get(("kv", P, N)), by.get(("nocache", P, N))
            sp = f"{a['decode_tok_s_median'] / b['decode_tok_s_median']:.1f}" if a and b else "--"
            rows.append([str(P), str(N), f(a and a["decode_tok_s_median"], 2), f(b and b["decode_tok_s_median"], 2),
                         sp, f(a and a["peak_rss_mb_median"], 0), f(a and a["kv_analytical_mb"], 1)])
        srcs = ", ".join(os.path.relpath(x, ROOT) for x in (kv, nc) if x)
        table("kvcache", srcs + (f", {os.path.relpath(eq, ROOT)}" if eq else ""),
              tab("rrrrrrr", ["$P$", "$N$", "KV tok/s", "No-cache tok/s", "Speed-up", "Peak RSS (MB)",
                              "KV formula (MB)"], rows),
              "Decode throughput (median) with and without KV cache, peak process memory, and analytical KV size. "
              "Equivalence: Table~\\ref{tab:kveq}. Missing cells were not measured.", "tab:kv", wide=True)
        # include equivalence table in same file for the \maybeinput
        with open(os.path.join(TAB, "kvcache.tex"), "a") as fh:
            if eq:
                fh.write("\\input{tables/kvcache_equiv}\n")
        if sk and sn:
            fig, ax = plt.subplots(figsize=(3.4, 2.3))
            for i, (mode, ss) in enumerate((("kv", sk), ("nocache", sn))):
                xs = sorted(ss, key=lambda r: (r["P"], r["N"]))
                lab = "KV cache" if mode == "kv" else "No cache"
                ax.plot([r["P"] + r["N"] for r in xs], [r["decode_tok_s_median"] for r in xs], "o-", ms=3,
                        color=OKABE[i], label=lab)
            ax.set_xlabel("Total sequence length $P+N$ (tokens)")
            ax.set_ylabel("Decode throughput (tokens/s)")
            ax.set_yscale("log")
            ax.legend(frameon=False)
            savefig(fig, "kvcache_latency")


