def finetune():
    rows = []
    for p in sorted(glob.glob(os.path.join(R, "finetune", "*", "summary.json"))):
        s = json.load(open(p))
        run = os.path.basename(os.path.dirname(p))
        rows.append([esc(run), esc(s.get("base_model", "").split("/")[-1]), str(s.get("n_examples", "--")),
                     str(s.get("optimizer_steps", "--")), f(s.get("loss_mean_first_k"), 3),
                     f(s.get("loss_mean_last_k"), 3), f(s.get("sec_per_step_mean"), 1),
                     f(s.get("peak_rss_mb"), 0), f(s.get("wall_s"), 0)])
    if not rows:
        MISSING.append("finetune/*/summary.json")
        print("[skip] no finetune summaries")
        return
    table("finetune_summary", "results/finetune/*/summary.json",
          tab("llrrrrrrr", ["Run", "Base", "Ex.", "Steps", "Loss first-$k$", "Loss last-$k$", "s/step", "RSS (MB)",
                            "Wall (s)"], rows),
          "Fine-tuning runs (LoRA, CPU): mean training loss over the first and last $k$ optimizer steps, "
          "step time, peak resident memory and wall time.", "tab:finetune", wide=True)
    logs = [p for p in sorted(glob.glob(os.path.join(R, "finetune", "*", "train_log.csv")))]
    if logs:
        fig, ax = plt.subplots(figsize=(3.4, 2.2))
        for i, p in enumerate(logs):
            rr = cload(p)
            ax.plot([int(r["step"]) for r in rr], [float(r["loss"]) for r in rr], color=OKABE[i % 8],
                    label=os.path.basename(os.path.dirname(p)))
        ax.set_xlabel("Optimizer step")
        ax.set_ylabel("Training loss (nats/token)")
        ax.legend(frameon=False)
