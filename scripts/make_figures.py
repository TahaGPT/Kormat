# ---------------------------------------------------------------- eval
def load_eval():
    out = {}
    for model in ("base", "ft"):
        for sp, rel in (("val", f"eval/val_{model}"), ("test", f"eval/test_final/{model}")):
            d = jload(rel + "/metrics.json")
            if d:
                out[(model, sp)] = d
    return out


def ci(d, k):
    c = d.get("ci", {}).get(k)
    return f"{c['point']:.3f} [{c['lo']:.3f}, {c['hi']:.3f}]" if c else f(d["classification"]["overall"][k])


def eval_tables(ev):
    if not ev:
        return
    rows = []
    notes = []
    for sp in ("val", "test"):
        for model in ("base", "ft"):
            d = ev.get((model, sp))
            if not d:
                continue
            c = d["classification"]
            n = d["n"]
            if d.get("complete") is False:
                notes.append(f"{model}/{sp}: n={n} of {d.get('n_requested')} requested (incomplete)")
            name = "Fine-tuned" if model == "ft" else "Base"
            rows.append([name, sp, str(n), ci(d, "accuracy"), ci(d, "macro_f1"),
                         f(c["inclusion"]["accuracy"]), f(c["inclusion"]["macro_f1"]),
                         f(c["exclusion"]["accuracy"]), f(c["exclusion"]["macro_f1"]),
                         f(d.get("invalid_rate"))])
    cap = ("Label classification. Overall accuracy and macro-F1 with 95\\% bootstrap CI (1000 resamples, where "
           "available); inclusion/exclusion subsets; rate of unparseable (INVALID) outputs.")
    if notes:
        cap += " Incomplete runs: " + esc("; ".join(notes)) + "."
    table("eval_before_after", "results/eval/{val_ft,val_base,test_final/{ft,base}}/metrics.json",
          tab("llrrrrrrr", ["Model", "Split", "$n$", "Acc.\\ [CI]", "Macro-F1 [CI]", "Inc.\\ Acc", "Inc.\\ F1",
                            "Exc.\\ Acc", "Exc.\\ F1", "Invalid"][:0] or
              ["Model", "Split", "$n$", "Acc.\\ [95\\% CI]", "Macro-F1 [95\\% CI]", "Inc.\\ Acc", "Inc.\\ F1",
               "Exc.\\ Acc", "Exc.\\ F1", "Invalid"], rows).replace("{llrrrrrrr}", "{llrllrrrrr}"),
          cap, "tab:cls", wide=True)

    # per-class table, ft test else val
    for model in ("ft", "base"):
        pass
    key = next(((m, s) for s in ("test", "val") for m in ("ft",) if (m, s) in ev), None)
    if key:
        d = ev[key]
        rows = []
        for ty in ("inclusion", "exclusion"):
            pc = d["classification"][ty]["per_class"]
            for l in CLS_ORDER:
                if l in pc:
                    p = pc[l]
                    rows.append([ty, esc(l), f(p["precision"]), f(p["recall"]), f(p["f1"]), str(p["support"])])
        note = "" if key[1] == "test" else " (validation split; test results not yet available)"
        table("perclass_prf", f"results/eval/{'test_final' if key[1]=='test' else 'val_ft'}/metrics.json",
              tab("llrrrr", ["Type", "Class", "P", "R", "F1", "Support"], rows),
              f"Per-class precision, recall and F1 of the fine-tuned model on the {key[1]} split{note}.",
              "tab:perclass")

    # evidence table
    rows = []
    for sp in ("val", "test"):
        for model in ("base", "ft"):
            d = ev.get((model, sp))
            if not d:
                continue
            e = d["evidence"]
            c = e["cells"]
            rows.append(["Fine-tuned" if model == "ft" else "Base", sp,
                         f(e["micro"]["precision"]), f(e["micro"]["recall"]), f(e["micro"]["f1"]),
                         f(e["macro_all"]["f1"]), f(e["macro_nonempty_gold"]["f1"]),
                         str(e["macro_nonempty_gold"]["n"]),
                         f"{c['gold_empty_pred_empty']}/{c['gold_empty_pred_nonempty']}/"
                         f"{c['gold_nonempty_pred_empty']}/{c['gold_nonempty_pred_nonempty']}"])
    table("evidence_prf", "results/eval/*/metrics.json (evidence)",
          tab("llrrrrrrr", ["Model", "Split", "P", "R", "F1", "Macro F1 (all)", "Macro F1 (non-empty)",
                            "$n_{ne}$", "Cells"], rows),
          "Evidence-sentence retrieval. P/R/F1 are micro-averaged over sentence IDs; macro averages are per "
          "record, over all records or only those with non-empty gold evidence ($n_{ne}$). Cells = counts of "
          "(gold empty, pred empty)/(gold empty, pred non-empty)/(gold non-empty, pred empty)/"
          "(both non-empty).", "tab:evidence", wide=True)

    # confusion matrices
    for (model, sp), d in ev.items():
        for ty in ("overall", "inclusion", "exclusion"):
            cf = d["classification"][ty]["confusion"]
            labs, M = cf["labels"], cf["matrix"]
            rows_l = [l for l in CLS_ORDER if l in labs and any(M[labs.index(l)])] if False else \
                [l for l in labs[:len(M)]]
            keep = [i for i, l in enumerate(rows_l) if sum(M[i]) > 0]
            colkeep = [j for j in range(len(labs)) if any(M[i][j] for i in range(len(M))) or labs[j] in
                       [rows_l[i] for i in keep]]
            fig, ax = plt.subplots(figsize=(3.2, 2.8))
            sub = [[M[i][j] for j in colkeep] for i in keep]
            im = ax.imshow(sub, cmap="Blues")
            ab = lambda l: l.replace("not enough information", "NEI").replace("not applicable", "N/A")
            ax.set_xticks(range(len(colkeep)))
            ax.set_xticklabels([ab(labs[j]) for j in colkeep], rotation=40, ha="right")
            ax.set_yticks(range(len(keep)))
            ax.set_yticklabels([ab(rows_l[i]) for i in keep])
            ax.set_xlabel("Predicted label")
            ax.set_ylabel("Gold label")
            mx = max(max(r) for r in sub) or 1
            for a, r in enumerate(sub):
                for b, v in enumerate(r):
                    ax.text(b, a, v, ha="center", va="center", fontsize=7, color="white" if v > mx / 2 else "black")
            savefig(fig, f"confusion_{model}_{sp}_{ty}")

    # before/after delta
    sp = next((s for s in ("test", "val") if ("base", s) in ev and ("ft", s) in ev), None)
    if sp:
        b, t = ev[("base", sp)], ev[("ft", sp)]
        labs = [l for l in CLS_ORDER if l in t["classification"]["overall"]["per_class"]
                and l in b["classification"]["overall"]["per_class"]]
        dl = [t["classification"]["overall"]["per_class"][l]["f1"] - b["classification"]["overall"]["per_class"][l]["f1"]
              for l in labs]
        fig, ax = plt.subplots(figsize=(3.4, 2.3))
        ax.bar(range(len(labs)), dl, color=[OKABE[2] if x >= 0 else OKABE[3] for x in dl])
        ax.axhline(0, color="k", lw=0.5)
        ax.set_xticks(range(len(labs)))
        ax.set_xticklabels([l.replace("not enough information", "NEI").replace("not applicable", "N/A")
                            for l in labs], rotation=30, ha="right")
        ax.set_ylabel(f"$\\Delta$ F1 (fine-tuned $-$ base, {sp})")
        savefig(fig, "f1_delta")
    else:
        print("[skip] f1_delta.pdf: need base and ft on the same split")


